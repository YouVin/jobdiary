import { describe, expect, it } from 'vitest';
import { normalizeDeadline } from './dateNormalize';

describe('normalizeDeadline', () => {
  it.each([
    ['2026-10-28', '2026-10-28'],
    ['2026.10.28', '2026-10-28'],
    ['2026. 7. 1', '2026-07-01'],
    [' 2026.10.28(수) 23:59 ', '2026-10-28'],
    ['2026.10.28.', '2026-10-28'],
    ['2026/7/1', '2026-07-01'],
    ['2026년 10월 28일 (수) 18:00', '2026-10-28'],
    ['2028.02.29', '2028-02-29'],
    ['2026.01.01 00:00', '2026-01-01'],
  ])('%s를 날짜만 있는 %s로 변환한다', (raw, expected) => {
    expect(normalizeDeadline(raw)).toBe(expected);
  });

  it.each([
    undefined, '', ' ', '상시채용', '채용 시 마감', 'D-3', '오늘 마감', '마감',
    '10.28', '26.10.28', '2026.02.29', '2026.02.31', '2026.13.01',
    '2026.00.01', '2026.10.00', '2026.10.32', '0000.01.01',
    '2026.10.28 24:00', '2026.10.28 23:60', '2026-10.28',
    '2026.10.01 ~ 2026.10.28', '상시채용 (2026.10.28)',
    '지원일 2026.10.28', '2026.10.28 마감 예정', '2026-10-28T23:59:00Z',
  ])('불확실하거나 유효하지 않은 %s는 생략한다', (raw) => {
    expect(normalizeDeadline(raw)).toBeUndefined();
  });
});
